"""Resolve retired regional IDs without creating duplicate company records."""
import json
import re

ID = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def redirects(root):
    path = root / "data/lists/company-redirects.json"
    if not path.exists():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    if set(data) != {"schema_version", "redirects"} or data["schema_version"] != 1 or not isinstance(data["redirects"], dict):
        raise ValueError("Invalid company redirect map")
    routes = data["redirects"]
    for old, target in routes.items():
        if not ID.fullmatch(old) or not isinstance(target, str) or not ID.fullmatch(target):
            raise ValueError("Invalid company redirect ID")
        if target in routes:
            raise ValueError("Company redirects must point directly to canonical IDs, without cycles")
        if (root / "data/companies" / (old + ".json")).exists():
            raise ValueError("Retired company ID must not remain a separate record")
        if not (root / "data/companies" / (target + ".json")).is_file():
            raise ValueError("Company redirect target is missing")
    return routes


def canonical_id(root, value):
    return redirects(root).get(value, value)


def render(root):
    banner = "<!-- Generated by tools/build.py from canonical JSON. Do not edit by hand. -->\n\n"
    out = {}
    for old, target in redirects(root).items():
        record = json.loads((root / "data/companies" / (target + ".json")).read_text())
        out["data/views/companies/" + old + ".md"] = (
            banner + "# 已并入公司档案\n\n"
            + "原地区条目 `" + old + "` 已归入 [" + record["name"] + "](" + target + ".md)。\n\n"
            + "地区业务、地点、渠道与证据在主公司档案中维护；本页只兼容旧链接，不计为另一家公司。\n\n"
            + "[公司原始 JSON](../../companies/" + target + ".json) · [返回索引](../README.md)\n"
        )
    return out
